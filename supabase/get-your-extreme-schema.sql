-- Get Your Extreme Supabase schema
-- Run this in Supabase SQL Editor for the new project.

create extension if not exists pgcrypto;

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('SUP', 'BIKE', 'SKI')),
  date date not null,
  time text,
  duration_hours numeric not null,
  route_distance_km numeric,
  capacity integer not null,
  booked integer not null default 0,
  price numeric,
  whatsapp_contact_required boolean not null default false,
  title text not null,
  summary text not null,
  details text not null,
  service_stops text[] not null default '{}',
  created_at timestamptz not null default now()
);

alter table public.events
add column if not exists route_distance_km numeric;

alter table public.events alter column time drop not null;
alter table public.events alter column price drop not null;
alter table public.events
add column if not exists whatsapp_contact_required boolean not null default false;

create index if not exists events_date_time_idx on public.events (date, time);
create index if not exists events_category_date_idx on public.events (category, date);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  activity text not null,
  route text not null,
  date date not null,
  status text not null default 'Pending',
  timestamp timestamptz not null default now(),
  source text,
  amount numeric,
  event_id text,
  referred_by_code text
);

create index if not exists reservations_date_idx on public.reservations (date);
create index if not exists reservations_event_id_idx on public.reservations (event_id);

create table if not exists public.qr_codes (
  id uuid primary key default gen_random_uuid(),
  key text not null unique,
  url text not null,
  data_url text,
  updated_at timestamptz not null default now()
);

insert into public.qr_codes (key, url, data_url, updated_at)
values ('main_site', 'https://www.getyourextreme.com/', '', now())
on conflict (key) do nothing;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  ref_code text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin', 'customer')),
  created_at timestamptz not null default now()
);

-- The current app uses the publishable key directly for public bookings,
-- event reads, admin event writes after sign-in, and QR updates. Keep RLS
-- disabled unless you add matching policies for all app workflows.
alter table public.events disable row level security;
alter table public.reservations disable row level security;
alter table public.qr_codes disable row level security;
alter table public.profiles disable row level security;
alter table public.user_roles disable row level security;

